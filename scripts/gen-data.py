def _man_command(node: Node, aliases: list[str], global_set: set[str]) -> list[str]:
    """The ``.SS`` section of one command: synopsis, help, its own options and positionals."""
    title = node.key
    if len(aliases) > 1:
        title += " (alias: " + ", ".join(aliases[1:]) + ")"
    lines = [f".SS {roff(title)}", _synopsis(node), ".PP", roff(node.help or "")]
    for option in node.options:
        if not set(option.flags) <= global_set:
            lines += [".TP", _option_label(option), roff(option.help or "")]
    for metavar, help_text, choices in node.positionals:
        text = help_text
        if choices:
            text = (text + " " if text else "") + "One of: " + ", ".join(choices) + "."
        lines += [".TP", f"\\fI{roff(metavar.upper())}\\fR", roff(text)]
    return lines


def _man_commands(tree: Node) -> list[str]:
    """The COMMANDS section of fork-linux(1)."""
    aliases: dict[int, list[str]] = {}
    for name, _help, child in tree.subcommands:
        aliases.setdefault(id(child), []).append(name)
    global_set = set(global_flags(tree)) | {"-h", "--help"}
    lines = [".SH COMMANDS"]
    for node in walk(tree)[1:]:
        lines += _man_command(node, aliases.get(id(node), []), global_set)
    return lines


