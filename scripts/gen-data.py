#!/usr/bin/env python3
"""Generate the installed data files of Fork for Linux (unofficial) from their single sources.

* ``desktop OUT``          the system menu entry, rendered from
  ``src/fork_linux/data/templates/io.github.ventura8.ForkLinux.desktop.in``
  exactly like the per-user one (``desktop_integration``), with ``Exec=fork-linux``;
* ``metainfo IN OUT``      the AppStream metainfo: ``@APP_ID@`` / ``@APP_NAME@`` and the
  ``@DESCRIPTION@`` paragraphs from ``credits.render_metainfo_paragraphs()``;
* ``fm-action KIND OUT``   a system-wide "Open in Fork" file-manager action
  (``nautilus``, ``nemo``, ``dolphin``, ``fma``) from the same templates;
* ``completions SHELL``    bash / zsh / fish completions generated from the argparse parser;
* ``man PAGE``             the ``fork-linux.1`` / ``fork.1`` manual pages, from the parser too;
* ``write`` / ``check``    regenerate (or verify, exit 1 on drift) the committed
  ``data/completions/*`` and ``data/man/*``.

Meson runs the first three at build time; the completions and manual pages are
committed (so the lint stage can run ``bash -n`` / ``zsh -n`` / ``fish -n`` on them) and
``tests/test_completions.py`` / ``tests/test_manpages.py`` fail when they drift.
"""

