def committed_outputs() -> dict[Path, str]:
    """Every committed generated file and its expected content."""
    tree = load_tree()
    out: dict[Path, str] = {}
    for (kind, name), rel in COMMITTED.items():
        out[rel] = render_completions(name, tree) if kind == "completions" else render_man(name, tree)
    return out


def safe_path(raw: str | Path) -> Path:
    """``raw`` resolved, refused unless it lies in the repository or the working directory.

    Meson runs this script from its build directory and passes paths inside it; ``write`` /
    ``check`` use repository paths. Anything else (``..`` escapes, absolute paths elsewhere,
    symlinks pointing out) is a usage error.
    """
    resolved = Path(os.path.realpath(raw))
    bases = (Path(os.path.realpath(ROOT)), Path(os.path.realpath(os.getcwd())))
    if not any(resolved == base or resolved.is_relative_to(base) for base in bases):
        raise SystemExit(f"gen-data.py: refusing {raw}: outside the repository and the build directory")
    return resolved


def _write(path: str | Path, text: str) -> None:
    target = safe_path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")


def _read(path: str | Path) -> str:
    return safe_path(path).read_text(encoding="utf-8")


def _emit(text: str, out: str | None) -> None:
    if out is None:
        sys.stdout.write(text)
    else:
        _write(out, text)


def _cmd_name(args: argparse.Namespace) -> int:
    _import_package()
    import fork_linux

    print(getattr(fork_linux, args.key))
    return 0


def _cmd_write(_args: argparse.Namespace) -> int:
    for rel, text in committed_outputs().items():
        _write(ROOT / rel, text)
        print(f"wrote {rel}")
    return 0


def _cmd_check(_args: argparse.Namespace) -> int:
    drift = [
        str(rel)
        for rel, text in committed_outputs().items()
        if not (ROOT / rel).is_file() or _read(ROOT / rel) != text
    ]
    if drift:
        print("gen-data.py: out of date (run scripts/gen-data.py write): " + ", ".join(drift), file=sys.stderr)
        return 1
    print("gen-data.py: completions and manual pages are up to date")
    return 0


def _written(render: Callable[[argparse.Namespace], str]) -> Callable[[argparse.Namespace], int]:
    """A handler that writes ``render(args)`` to ``args.out`` (stdout when there is none)."""

    def handler(args: argparse.Namespace) -> int:
        _emit(render(args), args.out)
        return 0

    return handler


HANDLERS: dict[str, Callable[[argparse.Namespace], int]] = {
    "desktop": _written(lambda _args: render_desktop()),
    "metainfo": _written(lambda args: render_metainfo(_read(args.template))),
    "fm-action": _written(lambda args: render_fm_action(args.kind)),
    "build-info": _written(lambda args: render_build_info(args.version, args.flavor)),
    "completions": _written(lambda args: render_completions(args.shell)),
    "man": _written(lambda args: render_man(args.page)),
    "name": _cmd_name,
    "write": _cmd_write,
    "check": _cmd_check,
}


def build_cli() -> argparse.ArgumentParser:
    """The command-line parser."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("desktop").add_argument("out")
    p_meta = sub.add_parser("metainfo")
    p_meta.add_argument("template")
    p_meta.add_argument("out")
    p_fm = sub.add_parser("fm-action")
    p_fm.add_argument("kind", choices=FM_KINDS)
    p_fm.add_argument("out")
    p_comp = sub.add_parser("completions")
    p_comp.add_argument("shell", choices=("bash", "zsh", "fish"))
    p_comp.add_argument("out", nargs="?")
    p_man = sub.add_parser("man")
    p_man.add_argument("page", choices=("fork-linux", "fork"))
    p_man.add_argument("out", nargs="?")
    p_build = sub.add_parser("build-info")
    p_build.add_argument("version")
    p_build.add_argument("flavor")
    p_build.add_argument("out")
    sub.add_parser("name").add_argument("key", choices=("APP_ID", "APP_NAME", "PACKAGE"))
    sub.add_parser("write")
    sub.add_parser("check")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    args = build_cli().parse_args(argv)
    return HANDLERS[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
