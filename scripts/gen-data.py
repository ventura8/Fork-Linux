def render_man_fork(tree: Node) -> str:
    """``fork(1)``."""
    lines = _man_header("fork", "User Commands")
    lines += [
        ".SH NAME",
        "fork \\- open repositories in Fork for Linux (unofficial)",
        ".SH SYNOPSIS",
        "\\fBfork\\fR [\\fIOPTIONS\\fR] [\\fIPATH\\fR...]",
        ".br",
        "\\fBfork open\\fR [\\fIOPTIONS\\fR] \\fIPATH\\fR...",
        ".br",
        "\\fBfork\\fR \\fB\\-\\-help\\fR | \\fB\\-\\-version\\fR",
        ".SH DESCRIPTION",
        roff(
            "Open each PATH (a repository, or a file or folder inside one) in Fork. With no PATH, "
            "start Fork. This is a shortcut for 'fork-linux run'; the first run sets everything up. "
            "Use -- before paths that start with '-'."
        ),
        ".SH OPTIONS",
        ".TP",
        "\\fB\\-h\\fR, \\fB\\-\\-help\\fR",
        roff("Show the usage and exit."),
        ".TP",
        "\\fB\\-V\\fR, \\fB\\-\\-version\\fR",
        roff("Show the version and exit."),
    ]
    for option in tree.options:
        if set(option.flags) & {"--json", "-h", "--help", "-V", "--version"}:
            continue
        lines += [".TP", _option_label(option), roff(option.help or "")]
    lines += [
        ".SH EXIT STATUS",
        roff("The exit status of fork-linux run; see fork-linux(1)."),
    ]
    lines += _credits_section()
    lines += [".SH SEE ALSO", "\\fBfork\\-linux\\fR(1)"]
    return "\n".join(lines) + "\n"


def render_man(page: str, tree: Node | None = None) -> str:
    """The manual page ``page`` (``fork-linux`` or ``fork``)."""
    node = load_tree() if tree is None else tree
    if page == "fork-linux":
        return render_man_fork_linux(node)
    if page == "fork":
        return render_man_fork(node)
    raise SystemExit(f"gen-data.py: unknown manual page {page!r} (choose from fork-linux, fork)")


def render_build_info(version: str, flavor: str) -> str:
    """``fork_linux/_build.py``: the version and packaging flavour baked in at build time."""
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise SystemExit(f"gen-data.py: invalid version {version!r}")
    if not re.fullmatch(r"[a-z0-9][a-z0-9.-]*", flavor):
        raise SystemExit(f"gen-data.py: invalid flavor {flavor!r}")
    return (
        '"""Build information generated by meson (scripts/gen-data.py build-info); do not edit."""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        f'VERSION = "{version}"\n'
        f'FLAVOR = "{flavor}"\n'
    )


